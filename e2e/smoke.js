// Smoke test against a web export served on :8081. Usage: npx expo export -p web && (serve dist) && node e2e/smoke.js <screenshot-dir>
// Requires: npm i -D playwright (not installed by default). CHROME env var can point to a Chromium binary.
const { chromium } = require('playwright');
const out = process.argv[2];
(async () => {
  const b = await chromium.launch({ executablePath: process.env.CHROME || undefined });
  const p = await b.newPage({ viewport: { width: 412, height: 900 } });
  const errors = [];
  p.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
  p.on('console', (m) => m.type() === 'error' && errors.push('console: ' + m.text()));
  p.on('dialog', (d) => d.accept());
  await p.goto('http://localhost:8081/', { waitUntil: 'networkidle' });
  await p.getByTestId('create-character').click();
  await p.waitForTimeout(500);
  // Step 1: class wizard (default) level 4
  for (let i = 0; i < 3; i++) await p.getByRole('button', { name: '+' }).first().click();
  await p.screenshot({ path: out + '/10-wizard-class.png' });
  await p.getByTestId('wizard-next').click();
  await p.getByText('Humano', { exact: true }).click();
  await p.getByTestId('wizard-next').click();
  await p.getByText('Sabio', { exact: true }).click();
  await p.getByTestId('wizard-next').click();
  await p.screenshot({ path: out + '/11-wizard-abilities.png' });
  await p.getByTestId('wizard-next').click();
  await p.getByText('Arcanos', { exact: true }).click();
  await p.getByText('Perspicacia', { exact: true }).click();
  await p.getByTestId('wizard-next').click();
  await p.getByTestId('wizard-next').click();
  await p.getByTestId('wizard-name').fill('Angvel');
  await p.getByTestId('wizard-create').click();
  await p.waitForTimeout(800);
  await p.screenshot({ path: out + '/12-sheet.png', fullPage: true });
  await p.getByTestId('btn-damage').click();
  await p.getByRole('button', { name: '+10' }).click();
  await p.getByTestId('apply-hp').click();
  await p.waitForTimeout(300);
  const hp = await p.getByTestId('hp-value').innerText();
  console.log('hp after 10 dmg:', hp);
  await p.getByTestId('skill-arcana').click();
  await p.waitForTimeout(300);
  await p.screenshot({ path: out + '/13-roll.png' });
  await p.getByText('Conjuros', { exact: true }).click();
  await p.getByTestId('add-spell').click();
  await p.getByTestId('picker-search').fill('proyectil');
  await p.waitForTimeout(400);
  await p.getByText('Proyectil mágico', { exact: true }).click();
  await p.waitForTimeout(300);
  await p.getByTestId('cast-Magic Missile').click();
  await p.getByTestId('slot-1').click();
  await p.waitForTimeout(300);
  await p.screenshot({ path: out + '/14-spells.png', fullPage: true });
  await p.getByText('Combate', { exact: true }).click();
  await p.getByTestId('btn-long-rest').click();
  await p.waitForTimeout(300);
  console.log('hp after long rest:', await p.getByTestId('hp-value').innerText());
  await p.screenshot({ path: out + '/15-combat.png', fullPage: true });
  console.log('errors:', JSON.stringify(errors.slice(0, 10)));
  await b.close();
})().catch((e) => { console.error(e.message); process.exit(1); });
